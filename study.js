      var q = list[+box.dataset.n];
      box.classList.add('done'); answered++;
      if (q.t === 'sa') { score(); return; }
      var correct = q.t === 'mc' ? q.a : (q.a ? 1 : 0);
      var picked = +b.dataset.i;
      box.querySelectorAll('.opts button').forEach(function(x){ if (+x.dataset.i === correct) x.classList.add('ok'); });
